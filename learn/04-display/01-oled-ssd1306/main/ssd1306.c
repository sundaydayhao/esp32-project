/**
 * @brief 发送命令到 SSD1306
 */
static esp_err_t ssd1306_send_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};  // 0x00 = 命令模式
    return i2c_master_write_to_device(s_i2c_num, s_i2c_addr, buf, 2,
                                       pdMS_TO_TICKS(100));
}

/**
 * @brief 发送数据到 SSD1306
 */
static esp_err_t ssd1306_send_data(const uint8_t *data, size_t len)
{
    uint8_t *buf = malloc(len + 1);
    if (!buf) return ESP_ERR_NO_MEM;
    buf[0] = 0x40;  // 0x40 = 数据模式
    memcpy(buf + 1, data, len);
    esp_err_t ret = i2c_master_write_to_device(s_i2c_num, s_i2c_addr, buf, len + 1,
                                                pdMS_TO_TICKS(100));
    free(buf);
    return ret;
}

esp_err_t ssd1306_init(int i2c_num, uint8_t addr)
{
    s_i2c_num = i2c_num;
    s_i2c_addr = addr;

    /* SSD1306 初始化序列 */
    const uint8_t init_cmds[] = {
        0xAE,       // 关闭显示
        0xD5, 0x80, // 设置时钟分频
        0xA8, 0x3F, // 设置多路复用比（64行）
        0xD3, 0x00, // 设置显示偏移
        0x40,       // 设置起始行
        0x8D, 0x14, // 启用电荷泵
        0x20, 0x00, // 水平寻址模式
        0xA1,       // 列地址映射（翻转）
        0xC8,       // COM 扫描方向（翻转）
        0xDA, 0x12, // COM 引脚配置
        0x81, 0xCF, // 设置对比度
        0xD9, 0xF1, // 预充电周期
        0xDB, 0x40, // VCOMH 电压
        0xA4,       // 全局显示开启
        0xA6,       // 正常显示（非反转）
        0xAF,       // 开启显示
    };

    for (int i = 0; i < sizeof(init_cmds); i++) {
        esp_err_t ret = ssd1306_send_cmd(init_cmds[i]);
        if (ret != ESP_OK) {
            ESP_LOGE(TAG, "初始化失败，命令 0x%02X", init_cmds[i]);
            return ret;
        }
    }

    ssd1306_clear();
    ssd1306_refresh();

    ESP_LOGI(TAG, "SSD1306 初始化完成，地址: 0x%02X", addr);
    return ESP_OK;
}

void ssd1306_clear(void)
{
    memset(s_display_buf, 0, sizeof(s_display_buf));
}

esp_err_t ssd1306_refresh(void)
{
    /* 设置列地址范围 */
    ssd1306_send_cmd(0x21);
    ssd1306_send_cmd(0);
    ssd1306_send_cmd(SSD1306_WIDTH - 1);

    /* 设置页地址范围 */
    ssd1306_send_cmd(0x22);
    ssd1306_send_cmd(0);
    ssd1306_send_cmd(SSD1306_HEIGHT / 8 - 1);

    /* 发送显示数据 */
    return ssd1306_send_data(s_display_buf, sizeof(s_display_buf));
}

void ssd1306_draw_pixel(int x, int y, bool color)
{
    if (x < 0 || x >= SSD1306_WIDTH || y < 0 || y >= SSD1306_HEIGHT) return;

    int byte_idx = x + (y / 8) * SSD1306_WIDTH;
    int bit_idx = y % 8;

    if (color) {
        s_display_buf[byte_idx] |= (1 << bit_idx);
    } else {
        s_display_buf[byte_idx] &= ~(1 << bit_idx);
    }
}

void ssd1306_draw_hline(int x, int y, int width, bool color)
{
    for (int i = 0; i < width; i++) {
        ssd1306_draw_pixel(x + i, y, color);
    }
}

void ssd1306_draw_vline(int x, int y, int height, bool color)
{
    for (int i = 0; i < height; i++) {
        ssd1306_draw_pixel(x, y + i, color);
    }
}

void ssd1306_draw_rect(int x, int y, int width, int height, bool color)
{
    ssd1306_draw_hline(x, y, width, color);
    ssd1306_draw_hline(x, y + height - 1, width, color);
    ssd1306_draw_vline(x, y, height, color);
    ssd1306_draw_vline(x + width - 1, y, height, color);
}

void ssd1306_fill_rect(int x, int y, int width, int height, bool color)
{
    for (int j = 0; j < height; j++) {
        ssd1306_draw_hline(x, y + j, width, color);
    }
}

void ssd1306_draw_char(int x, int y, char c, bool color)
{
    if (c < 0x20 || c > 0x7A) c = '?';
    int idx = c - 0x20;

    for (int col = 0; col < 8; col++) {
        uint8_t line = font8x8[idx][col];
        for (int row = 0; row < 8; row++) {
            if (line & (1 << row)) {
                ssd1306_draw_pixel(x + col, y + row, color);
            }
        }
    }
}

void ssd1306_draw_string(int x, int y, const char *str, bool color)
{
    while (*str) {
        ssd1306_draw_char(x, y, *str, color);
        x += 8;
        if (x + 8 > SSD1306_WIDTH) {
            x = 0;
            y += 8;
        }
        str++;
    }
}

esp_err_t ssd1306_set_contrast(uint8_t contrast)
{
    ssd1306_send_cmd(0x81);
    return ssd1306_send_cmd(contrast);
}
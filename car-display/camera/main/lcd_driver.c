/* ============================================================
 * 内部状态
 * ============================================================ */
static struct {
    esp_lcd_panel_handle_t panel;
    esp_lcd_panel_io_handle_t io;
    lcd_config_t config;
    bool initialized;
    /* 行缓冲区 (用于缩放绘制) */
    uint16_t *line_buf;
    int       line_buf_size;
} s_lcd = {
    .initialized = false,
};

/* ============================================================
 * 内部辅助
 * ============================================================ */

static inline uint16_t rgb565_blend(uint16_t bg, uint16_t fg, uint8_t alpha)
{
    if (alpha == 0)   return bg;
    if (alpha == 255) return fg;

    uint8_t inv = 255 - alpha;
    uint8_t r = (((fg >> 11) & 0x1F) * alpha + ((bg >> 11) & 0x1F) * inv) >> 8;
    uint8_t g = (((fg >>  5) & 0x3F) * alpha + ((bg >>  5) & 0x3F) * inv) >> 8;
    uint8_t b = (((fg      ) & 0x1F) * alpha + ((bg      ) & 0x1F) * inv) >> 8;
    return (uint16_t)((r << 11) | (g << 5) | b);
}


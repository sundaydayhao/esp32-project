// -----------------------------------------------------------------------------
// RTL-SDR USB Host 配置
// -----------------------------------------------------------------------------
// ESP32-S3 作为 USB Host 直接驱动 RTL-SDR (RTL2832U + R820T2)
//
// 硬件连接（将 RTL-SDR USB 线剪断，按以下方式连接）：
//   RTL-SDR USB D+  (绿线) ──→ ESP32-S3 GPIO20
//   RTL-SDR USB D-  (白线) ──→ ESP32-S3 GPIO19
//   RTL-SDR USB GND (黑线) ──→ ESP32-S3 GND
//   RTL-SDR USB 5V  (红线) ──→ 外部 5V 电源（不要接 ESP32-S3 3.3V！）
//
// ESP32-S3 USB OTG 引脚固定为 GPIO19/GPIO20，无需配置

// 按键 GPIO（按下切换到 1090 MHz ADS-B 频率）

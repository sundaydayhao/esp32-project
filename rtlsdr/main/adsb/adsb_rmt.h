#pragma once

#include "esp_err.h"

// =============================================================================
// ADS-B 直接接收方案 - 使用 ESP32-S3 RMT 外设解码 Mode-S PPM 信号
// =============================================================================
//
// 硬件连接（无需 Raspberry Pi，完全自包含）：
//
//   1090MHz天线
//       │
//   1090MHz SAW带通滤波器 (EPCOS B3588 或 TDK B3588)  ~¥15
//       │
//   低噪声放大器 LNA (SPF5189Z 模块)  ~¥25
//       │
//   包络检波器 (BAT54肖特基二极管 + 100pF + 1kΩ)  ~¥2
//       │
//   比较器 (LM393, 阈值约0.5V)  ~¥2
//       │
//   ESP32-S3 GPIO (RMT 输入)
//
// 总成本约 ¥44，无需 RTL-SDR 和 Raspberry Pi
//
// Mode-S 信号特性：
//   - 载波频率：1090 MHz
//   - 调制方式：PPM (脉冲位置调制)
//   - 比特率：1 Mbps
//   - 每比特周期：2μs
//     - 比特1：前1μs高电平，后1μs低电平
//     - 比特0：前1μs低电平，后1μs高电平
//   - 前导码：8μs（4个0.5μs脉冲）
// =============================================================================

/**
 * @brief 初始化 RMT 直接接收器并启动解码任务
 *        接收到的消息会自动注入 ADS-B 解码器
 *
 * @return ESP_OK 成功
 */
esp_err_t adsb_rmt_init(void);